// Writes src/design-system/tokens.css from src/design-system/themes.json.
// Run after editing a theme: node scripts/tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const data = JSON.parse(readFileSync(here("../src/design-system/themes.json"), "utf8"));

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const ch = (h) => hex(h).join(" ");
// "a over b" at alpha t, in sRGB, as the browser's color-mix(in srgb) does.
const mix = (a, b, t) => hex(a).map((x, i) => Math.round(x * t + hex(b)[i] * (1 - t))).join(" ");

const base = `/* Generated by scripts/tokens.mjs from themes.json. Do not edit by hand. */
:root {
  /* type: the site face by default; the gallery's type switch sets data-type="plex" */
  --k-font-sans: "Hanken Grotesk";
  --k-font-serif: "IBM Plex Serif";
  /* one easing (the end screen's expo-out); springs are baked into --k-spring-* at startup */
  --k-ease: cubic-bezier(0.22, 1, 0.36, 1);
  --k-spring-quick: var(--k-ease);
  --k-spring-settle: var(--k-ease);
  --k-spring-bounce: var(--k-ease);
  --k-spring-quick-ms: 320ms;
  --k-spring-settle-ms: 400ms;
  --k-spring-bounce-ms: 560ms;
  /* radii, chosen once: tight for cards, controls and chips; pills for glass controls */
  --k-radius-chip: 4px;
  --k-radius-control: 6px;
  --k-radius-card: 8px;
  --k-radius-panel: 12px;
  --k-radius-pill: 999px;
  /* z layers */
  --k-z-rail: 10;
  --k-z-sticky: 20;
  --k-z-scrim: 39;
  --k-z-sheet: 40;
  --k-z-toast: 50;
  --k-z-confetti: 60;
  /* fixed gold for the coin, the medal and token counts in every theme */
  --k-coin-rim-1: ${data.coin.rim[0]};
  --k-coin-rim-2: ${data.coin.rim[1]};
  --k-coin-rim-3: ${data.coin.rim[2]};
  --k-coin-face-1: ${data.coin.face[0]};
  --k-coin-face-2: ${data.coin.face[1]};
  --k-coin-face-3: ${data.coin.face[2]};
}
:root[data-type="plex"] {
  --k-font-sans: "IBM Plex Sans";
}
`;

const block = (t) => {
  const s = data.status[t.dark ? "dark" : "light"];
  const d = [
    ["canvas", ch(t.canvas)], ["surface", ch(t.surface)], ["raised", ch(t.raised)],
    ["panel", mix(t.surface, t.canvas, 0.92)], ["line", mix(t.border, t.surface, 0.24)],
    ["text", ch(t.text)], ["muted", ch(t.muted)], ["border", ch(t.border)],
    ["gold", ch(t.gold)], ["math", ch(t.math)], ["reading", ch(t.reading)],
    ["accent", ch(t.accent)], ["accent-ink", ch(t.accentInk)],
    ["positive", ch(s.positive)], ["positive-bg", ch(s.positiveBg)], ["positive-ink", ch(s.positiveInk)],
    ["negative", ch(s.negative)], ["negative-bg", ch(s.negativeBg)], ["negative-ink", ch(s.negativeInk)],
    ["notice", ch(s.notice)], ["notice-bg", ch(s.noticeBg)], ["notice-ink", ch(s.noticeInk)],
  ];
  const lines = [];
  for (let i = 0; i < d.length; i += 3)
    lines.push("  " + d.slice(i, i + 3).map(([k, v]) => `--k-${k}: ${v};`).join(" "));
  return `/* prettier-ignore */\nhtml[data-theme="${t.id}"] {\n  color-scheme: ${t.dark ? "dark" : "light"};\n${lines.join("\n")}\n}\n`;
};

const css = base + data.themes.map(block).join("");
writeFileSync(here("../src/design-system/tokens.css"), css);
console.log(`tokens.css: ${data.themes.length} themes, ${css.split("\n").length} lines`);
