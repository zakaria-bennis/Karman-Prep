// WCAG 2.1 contrast for every text token on every surface token in all 12
// themes, and body text over each background world's brightest (dark) and
// darkest (light) spot. Writes contrast-report.md and exits 1 on any pair under
// 4.5:1 (3:1 for the 24px-and-up pairs). Run: node scripts/contrast.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BG_MAX_ALPHA } from "../src/design-system/backgrounds/alpha.ts";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const data = JSON.parse(readFileSync(here("../src/design-system/themes.json"), "utf8"));

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const lin = (c) => (c /= 255) <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
const L = (c) => 0.2126 * lin(c[0]) + 0.7152 * lin(c[1]) + 0.0722 * lin(c[2]);
const ratio = (a, b) => { const x = L(a), y = L(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
const mix = (a, b, t) => a.map((x, i) => Math.round(x * t + b[i] * (1 - t)));
const hex = (c) => "#" + c.map((x) => x.toString(16).padStart(2, "0")).join("");

const rows = [];
let fails = 0;
const check = (theme, text, surface, textRgb, surfaceRgb, floor = 4.5) => {
  const r = ratio(textRgb, surfaceRgb);
  const ok = r >= floor;
  if (!ok) fails++;
  rows.push({ theme, text, surface, hexT: hex(textRgb), hexS: hex(surfaceRgb), r, floor, ok });
};

for (const t of data.themes) {
  const s = data.status[t.dark ? "dark" : "light"];
  const canvas = rgb(t.canvas), surface = rgb(t.surface), raised = rgb(t.raised);
  const panel = mix(surface, canvas, 0.92);
  const surfaces = { canvas, surface, raised, panel };
  // Running and secondary text on every surface.
  const texts = { text: rgb(t.text), muted: rgb(t.muted), accent: rgb(t.accent), gold: rgb(t.gold), positive: rgb(s.positive), negative: rgb(s.negative), notice: rgb(s.notice) };
  for (const [tn, tc] of Object.entries(texts)) for (const [sn, sc] of Object.entries(surfaces)) check(t.id, tn, sn, tc, sc);
  // Ink on fills.
  check(t.id, "accent-ink", "accent", rgb(t.accentInk), rgb(t.accent));
  check(t.id, "positive-ink", "positive-bg", rgb(s.positiveInk), rgb(s.positiveBg));
  check(t.id, "negative-ink", "negative-bg", rgb(s.negativeInk), rgb(s.negativeBg));
  check(t.id, "notice-ink", "notice-bg", rgb(s.noticeInk), rgb(s.noticeBg));
  // KPI figures (24px and up) in muted on the panel: the 3:1 floor.
  check(t.id, "muted at 24px+", "panel", rgb(t.muted), panel, 3);
  // Body text over each background world's strongest mark (text at alpha over canvas):
  // in dark the mark is the brightest spot, in light the darkest.
  for (const [bg, a] of Object.entries(BG_MAX_ALPHA)) {
    const spot = mix(rgb(t.text), canvas, a);
    check(t.id, "text", `bg ${bg} ${t.dark ? "brightest" : "darkest"} (${a})`, rgb(t.text), spot);
    check(t.id, "muted", `bg ${bg} ${t.dark ? "brightest" : "darkest"} (${a})`, rgb(t.muted), spot);
  }
}

const worst = [...rows].sort((a, b) => a.r - b.r).slice(0, 12);
const byTheme = data.themes.map((t) => { const r = rows.filter((x) => x.theme === t.id); return `| ${t.id} | ${r.length} | ${r.filter((x) => !x.ok).length} | ${Math.min(...r.map((x) => x.r)).toFixed(2)} |`; });
const md = `# Contrast report

Generated by scripts/contrast.mjs on ${new Date().toISOString().slice(0, 10)}. WCAG 2.1 ratios, computed, not eyeballed.
Floor: 4.5:1 for text, 3:1 for figures of 24px and up. ${rows.length} pairs, ${fails} under the floor.

Pairs per theme: text, muted, accent, gold, positive, negative and notice as text on canvas, surface, raised and
panel; accent-ink on accent; the three pill inks on their fills; muted at 24px+ on panel (3:1); and text and muted
over each background world's strongest mark (the text colour at the world's max alpha over the canvas: the
brightest spot in a dark theme, the darkest in a light one).

| Theme | Pairs | Under floor | Lowest ratio |
| --- | ---: | ---: | ---: |
${byTheme.join("\n")}

## Lowest twelve pairs

| Theme | Text | On | Colours | Ratio | Floor | |
| --- | --- | --- | --- | ---: | ---: | --- |
${worst.map((x) => `| ${x.theme} | ${x.text} | ${x.surface} | ${x.hexT} on ${x.hexS} | ${x.r.toFixed(2)} | ${x.floor} | ${x.ok ? "ok" : "FAIL"} |`).join("\n")}

## Every pair under the floor

${fails ? rows.filter((x) => !x.ok).map((x) => `- ${x.theme}: ${x.text} on ${x.surface}, ${x.hexT} on ${x.hexS}, ${x.r.toFixed(2)}:1 (floor ${x.floor})`).join("\n") : "None."}
`;
writeFileSync(here("../contrast-report.md"), md);
console.log(`${rows.length} pairs, ${fails} under the floor; lowest ${worst[0].theme} ${worst[0].text} on ${worst[0].surface} ${worst[0].r.toFixed(2)}:1`);
if (fails) { for (const x of rows.filter((x) => !x.ok)) console.log(`FAIL ${x.theme} ${x.text} on ${x.surface}: ${x.hexT} on ${x.hexS} = ${x.r.toFixed(2)}`); process.exit(1); }
