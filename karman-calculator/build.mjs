import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createHash } from "node:crypto";
import { format, resolveConfig } from "prettier";
const root = path.dirname(fileURLToPath(import.meta.url));
async function writeChanged(file, content) {
  const previous = await readFile(file).catch(() => null);
  if (!previous || !previous.equals(Buffer.from(content))) await writeFile(file, content);
}
const parts = [
  "complex",
  "math",
  "regression",
  "model",
  "graph",
  "implicit",
  "extras",
  "ui",
  "start",
];
const source =
  '/* Generated from karman-calculator/lib by build.mjs. Original Karman code; no dependencies. */\n(() => {\n"use strict";\n' +
  (
    await Promise.all(parts.map((name) => readFile(path.join(root, "lib", `${name}.js`), "utf8")))
  ).join("\n") +
  "\n})();\n";
const formatted = await format(source, {
  ...(await resolveConfig(path.join(root, "../.prettierrc.json"))),
  parser: "babel",
});
await writeChanged(path.join(root, "src/calculator.js"), formatted);
const target = path.join(root, "../public/karman-calculator");
await mkdir(target, { recursive: true });
for (const file of ["index.html", "style.css", "calculator.js"])
  await writeChanged(path.join(target, file), await readFile(path.join(root, "src", file)));
console.log("Built original Karman calculator and copied static deployment assets.");

const digest = createHash("sha256");
for (const file of ["index.html", "style.css", "calculator.js"])
  digest.update(await readFile(path.join(root, "src", file)));
await writeChanged(
  path.join(root, "../src/components/calculator/standalone-build.ts"),
  `// Generated by karman-calculator/build.mjs.\nexport const CALCULATOR_BUILD = \"${digest.digest("hex").slice(0, 16)}\";\n`
);
