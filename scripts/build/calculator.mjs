// Calculator build (AR-36).
//
//   node scripts/build/calculator.mjs --styles           writes styles/generated.ts
//   node scripts/build/calculator.mjs --styles --check   exits 1 when generated.ts is out of date
//   node scripts/build/calculator.mjs                    same as --styles
//
// The shadow-root stylesheet is the vendored MathQuill CSS, tokens.css, base.css, then every other
// styles/*.css in sorted order, joined as `/* <path> */\n<css>`. Importing this module has no side
// effects; the CLI runs only when the file is the process entry.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";

// A string path, not `new URL(…)`: under jsdom the global URL is not one Node's fileURLToPath accepts.
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const STYLES = "src/components/calculator/styles";
const MATHQUILL_CSS = "vendor/mathquill/mathquill.css";
const MATHQUILL_JS = "vendor/mathquill/mathquill.js";
const GENERATED = `${STYLES}/generated.ts`;
const HEAD = [MATHQUILL_CSS, `${STYLES}/tokens.css`, `${STYLES}/base.css`];

/** Constructs shadow-root CSS may not use (AR-36), with the name an error reports. */
const FORBIDDEN = [
  [/@font-face/i, "@font-face"],
  [/url\(/i, "url()"],
  [/@tailwind/i, "@tailwind"],
  [/@apply/i, "@apply"],
  [/:global/i, ":global"],
  [/composes\s*:/i, "composes:"],
];

/**
 * Repository-relative stylesheet paths in concatenation order.
 * @param {string} root repository root
 * @returns {Promise<string[]>}
 */
export async function styleSources(root) {
  const entries = await readdir(join(root, STYLES));
  const rest = entries
    .filter((name) => name.endsWith(".css"))
    .map((name) => `${STYLES}/${name}`)
    .filter((path) => !HEAD.includes(path))
    .sort();
  return [...HEAD, ...rest];
}

/**
 * Throws when `css` holds a construct shadow-root CSS may not use (AR-36).
 * @param {string} file path named in the error
 * @param {string} css
 * @returns {void}
 */
export function assertShadowSafeCss(file, css) {
  for (const [pattern, name] of FORBIDDEN) {
    if (pattern.test(css))
      throw new Error(`${file}: ${name} is not allowed in shadow-root CSS (AR-36)`);
  }
}

/**
 * Builds the Prettier-formatted styles/generated.ts and writes it when `write` is true and it changed.
 * @param {{ write: boolean }} options
 * @returns {Promise<{ text: string; changed: boolean }>}
 */
export async function generateCalculatorStyles(options) {
  const parts = [];
  for (const path of await styleSources(ROOT)) {
    const css = await readFile(join(ROOT, path), "utf8");
    assertShadowSafeCss(path, css);
    parts.push(`/* ${path} */\n${css}`);
  }
  const css = parts.join("\n");
  const mathquill = await readFile(join(ROOT, MATHQUILL_JS), "utf8");
  const build = createHash("sha256")
    .update(css + mathquill)
    .digest("hex")
    .slice(0, 16);
  const source = [
    "// Generated by scripts/build/calculator.mjs --styles. Do not edit.",
    `export const CALCULATOR_CSS = ${JSON.stringify(css)};`,
    `export const CALCULATOR_BUILD = ${JSON.stringify(build)};`,
    "",
  ].join("\n");
  const target = join(ROOT, GENERATED);
  const text = await prettier.format(source, {
    ...(await prettier.resolveConfig(target)),
    parser: "typescript",
  });
  const current = await readFile(target, "utf8").catch(() => null);
  const changed = current !== text;
  if (options.write && changed) await writeFile(target, text);
  return { text, changed };
}

async function main(argv) {
  if (argv.includes("--check")) {
    const { changed } = await generateCalculatorStyles({ write: false });
    if (changed) {
      console.error(`${GENERATED} is out of date; run node scripts/build/calculator.mjs --styles`);
      process.exitCode = 1;
    }
    return;
  }
  const { changed } = await generateCalculatorStyles({ write: true });
  console.log(changed ? `${GENERATED} written` : `${GENERATED} is up to date`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
