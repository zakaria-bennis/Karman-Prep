// Generates the calculator skin colour table from the calculator's own themes
// (src/lib/calculator/theme/themes.ts), and the eager light-DOM chrome sheet, which gives each site
// theme of src/lib/themes/palettes.ts the chrome of the calculator theme it maps to (TH-5). Both outputs are Prettier-formatted with the repo
// config and drift-tested by src/lib/calculator/theme/generated.test.ts.
//
//   npx tsx scripts/calculator/generate-skin-colors.ts           writes both files
//   npx tsx scripts/calculator/generate-skin-colors.ts --check   exits 1 when either is stale
//
// Value imports stay off skin-colors.generated.ts (and roles.ts, which imports it from Task 5 on),
// so the generator still runs when that file is missing or conflicted.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";
import { buildSkinColors } from "../../src/lib/calculator/theme/derive";
import {
  COLOR_ROLES,
  CURVE_SLOTS,
  SKIN_IDS,
  type SkinId,
  type SkinPalette,
} from "../../src/lib/calculator/theme/skins";
import { CHROME_VARS, TONES, type ChromeRole } from "../../src/lib/calculator/theme/vars";
import { CALCULATOR_THEMES, SITE_THEME_SKINS } from "../../src/lib/calculator/theme/themes";
import { SITE_THEMES } from "../../src/lib/themes/palettes";

type SkinTable = Readonly<Record<SkinId, { normal: SkinPalette }>>;

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = "scripts/calculator/generate-skin-colors.ts";
const HEADER = `Generated by ${SOURCE} from src/lib/calculator/theme/themes.ts (TH-5). Do not edit.`;
const CHROME_ROLES = Object.keys(CHROME_VARS) as ChromeRole[];

export const GENERATED_FILES = {
  skinColors: "src/lib/calculator/theme/skin-colors.generated.ts",
  chromeCss: "src/components/calculator/calculator-chrome.generated.css",
} as const;

/** An object literal of `entries` in the given order, one key per line. */
function objectLiteral(entries: readonly (readonly [string, string])[]): string {
  return `{\n${entries.map(([key, value]) => `${key}: ${value},`).join("\n")}\n}`;
}

function paletteLiteral(palette: SkinPalette): string {
  return objectLiteral([
    ["dark", String(palette.dark)],
    ["roles", objectLiteral(COLOR_ROLES.map((r) => [r, JSON.stringify(palette.roles[r])]))],
    ["tones", objectLiteral(TONES.map((t) => [t, String(palette.tones[t])]))],
    ["curves", objectLiteral(CURVE_SLOTS.map((k) => [k, JSON.stringify(palette.curves[k])]))],
    ["fillAlpha", objectLiteral(CURVE_SLOTS.map((k) => [k, String(palette.fillAlpha[k])]))],
  ]);
}

/** The name the theme picker shows for each skin: "Classic", then each theme's own name. */
export function skinNames(themes: readonly { id: string; name: string }[]): Record<SkinId, string> {
  const names = { classic: "Classic" } as Record<SkinId, string>;
  for (const theme of themes) names[theme.id as SkinId] = theme.name;
  for (const id of SKIN_IDS) if (names[id] === undefined) throw new Error(`No theme ${id}`);
  return names;
}

/**
 * The TypeScript table of every skin's palette, keyed in `SKIN_IDS` order, and the skins' names
 * (unformatted).
 */
export function skinColorsModule(colors: SkinTable, names: Record<SkinId, string>): string {
  const table = objectLiteral(
    SKIN_IDS.map((id) => [id, objectLiteral([["normal", paletteLiteral(colors[id].normal)]])])
  );
  const nameTable = objectLiteral(SKIN_IDS.map((id) => [id, JSON.stringify(names[id])]));
  return [
    `// ${HEADER}`,
    `import type { SkinId, SkinPalette } from "./skins";`,
    ``,
    `export const SKIN_COLORS: Readonly<Record<SkinId, { normal: SkinPalette }>> = ${table};`,
    ``,
    `/** The theme picker's name for each skin (the theme's name; "Classic"). */`,
    `export const SKIN_NAMES: Readonly<Record<SkinId, string>> = ${nameTable};`,
    ``,
  ].join("\n");
}

function chromeDeclarations(colors: SkinTable, skin: SkinId): string {
  const roles = colors[skin].normal.roles;
  return CHROME_ROLES.map((role) => `${CHROME_VARS[role]}: ${roles[role]};`).join("\n");
}

/** A site theme's calculator skin (themes.ts SITE_THEME_SKINS). */
function siteSkin(siteTheme: string): SkinId {
  const skin = SITE_THEME_SKINS[siteTheme];
  if (skin === undefined) throw new Error(`Site theme ${siteTheme} has no calculator theme`);
  return skin;
}

/**
 * The light-DOM chrome sheet (unformatted): Warm ivory's skin on `:root`, Observatory on `:root`
 * under `prefers-color-scheme: dark`, then one `html[data-theme]` block per site theme with the
 * chrome of its calculator skin. `:root` (0,1,0) loses to `html[data-theme="<id>"]` (0,1,1), so the
 * fallback applies only to a missing or unknown id.
 */
export function chromeStylesheet(colors: SkinTable): string {
  const blocks = [
    `:root {\n${chromeDeclarations(colors, siteSkin("ivory"))}\n}`,
    `@media (prefers-color-scheme: dark) {\n:root {\n${chromeDeclarations(colors, siteSkin("observatory"))}\n}\n}`,
    ...SITE_THEMES.map(
      ({ id }) => `html[data-theme="${id}"] {\n${chromeDeclarations(colors, siteSkin(id))}\n}`
    ),
  ];
  return `/* ${HEADER} */\n${blocks.join("\n\n")}\n`;
}

/** Both generated files, repo-relative path to Prettier-formatted text. */
export async function generateSkinColorFiles(): Promise<Record<string, string>> {
  const colors = buildSkinColors(CALCULATOR_THEMES);
  const texts: Record<string, string> = {
    [GENERATED_FILES.skinColors]: skinColorsModule(colors, skinNames(CALCULATOR_THEMES)),
    [GENERATED_FILES.chromeCss]: chromeStylesheet(colors),
  };
  const out: Record<string, string> = {};
  for (const [path, text] of Object.entries(texts)) {
    const abs = join(REPO_ROOT, path);
    out[path] = await prettier.format(text, {
      ...(await prettier.resolveConfig(abs)),
      filepath: abs,
    });
  }
  return out;
}

/**
 * Write mode writes every generated file under `root` and returns their paths; check mode returns
 * the paths of the files missing or different under `root`.
 */
export async function syncSkinColorFiles(root: string, mode: "write" | "check"): Promise<string[]> {
  const files = await generateSkinColorFiles();
  const paths: string[] = [];
  for (const [path, text] of Object.entries(files)) {
    const abs = join(root, path);
    if (mode === "write") {
      await mkdir(dirname(abs), { recursive: true });
      await writeFile(abs, text);
      paths.push(path);
    } else if ((await readFile(abs, "utf8").catch(() => null)) !== text) {
      paths.push(path);
    }
  }
  return paths;
}

async function main(check: boolean): Promise<void> {
  const paths = await syncSkinColorFiles(REPO_ROOT, check ? "check" : "write");
  if (!check) {
    console.log(`Wrote ${paths.join(", ")}`);
  } else if (paths.length > 0) {
    console.error(
      `Generated skin colours are out of date: ${paths.join(", ")}. Run npx tsx ${SOURCE}`
    );
    process.exitCode = 1;
  } else {
    console.log("Generated skin colours are up to date.");
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv.includes("--check")).catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
