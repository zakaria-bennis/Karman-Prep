// The calculator's own theme list (founder decision, 2026-10-26): ten light and ten dark themes,
// separate from the site themes of src/lib/themes/palettes.ts, which the rest of the site keeps
// using. Each light theme is its own recipe (paper, list, chrome, keypad and accent all chosen),
// not a tint of one, so no two read alike. derive.ts turns each into a full skin palette and
// raises any colour that misses its contrast target (TH-4). Observatory, Charcoal, Forest and Plum
// keep the site themes' values, so in the quiz they match the page around them.
//
// Type-only imports keep this module free of runtime dependencies (the TH-5 generator imports it).
import type { ThemeSkinId } from "./skins";

export interface CalculatorTheme {
  id: ThemeSkinId;
  name: string;
  dark: boolean;
  /** The graph paper. */
  paper: string;
  /** The expression list and popovers. */
  list: string;
  /** The top bar and panel chrome. */
  chrome: string;
  /** The keypad's light keys. */
  key: string;
  /** The keypad's operator keys. */
  keyOperator: string;
  /** The ink; raised to 7:1 on every background above. */
  text: string;
  /** Secondary text; raised to 7:1 likewise. */
  muted: string;
  /** Edges of fields and keys; raised to 3:1 on the list, chrome and keys. */
  border: string;
  /** The gridlines' seed when it differs from the border (made neutral, TH-19). */
  grid?: string;
  /** The interactive colour: the Enter key, the focused row bar, ticks, toggles and focus. */
  accent: string;
  /** Text on the accent; the accent is moved until it has 7:1 with it. */
  accentLabel: string;
  /** The error colour's seed; raised to 7:1 on the list. */
  error: string;
}

