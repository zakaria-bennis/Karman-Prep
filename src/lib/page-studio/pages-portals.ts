function admin(
  id: string,
  title: string,
  dir: string,
  extra: Partial<StudioPage> = {}
): StudioPage {
  return {
    id: `admin.${id}`,
    area: "admin",
    title,
    path: `/admin${dir}`,
    file: `${A}${dir}/page.tsx`,
    as: "admin",
    ...extra,
  };
}

