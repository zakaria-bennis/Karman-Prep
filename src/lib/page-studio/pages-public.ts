// The marketing site, sign-up and start, the student portal, and its quizzes and tests: half of the
// Page Studio's page list (see inventory.ts for what each field means).
import type { StudioPage } from "./inventory";

const S = "src/app/(site)";
const STU = "src/app/dashboard/student";

function site(id: string, title: string, path: string, dir: string, hint?: string): StudioPage {
  return {
    id: `site.${id}`,
    area: "site",
    title,
    path,
    file: `${S}${dir}/page.tsx`,
    as: "visitor",
    hint,
  };
}

function tab(id: string, title: string, hint?: string): StudioPage {
  return {
    id: `student.${id}`,
    area: "student",
    title,
    path: `/dashboard/student?page=${id}`,
    file: `${STU}/page.tsx`,
    as: "student",
    hint,
  };
}

